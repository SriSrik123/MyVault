#!/usr/bin/env python3
"""Generate answers400.tex -- the cover-page self-grading table (styleguide
"Please fill in the following table putting in expected points...").

Point values per part were NOT invented -- they're printed directly in the
original 163Exm2A.pdf, as a bare number immediately before each problem's
(and each lettered sub-part's) instruction text (e.g. "6 (1a) Expand..."
then "3 (i) (b-ax)^c" ... "3 (ii) (c-x+y)^(1+a)"). Extracted via
`pdftotext -layout` over the whole exam and cross-checked that each
problem's sub-part values sum to its own printed total:
  1a: 3+3=6      1b: 3+3=6      1c: 1+1+1+2=5 (parts i-iv, p411-415)
  2a: 6 (no sub-parts printed -- one lump)
  2b: 6 (no sub-parts printed -- one lump)
  2c: 5 (no sub-parts printed -- one lump)
  3a: 2+4=6      (conjecture=2, induction proof=4, p424)
  3b: 6 (no sub-parts printed -- one lump)
  3c: 1+1=2 (3c1, p428-429) + 1+2=3 (3c2, p430-431) = 5 for the combined
      "3c" row (the grading table has one row per problem letter, not
      one per 3c1/3c2 -- matches printed total 2+3=5)
Grand total: 6+6+5+6+6+5+6+6+5 = 51.

Every one of these 9 problems was fully built, and every math step
independently re-verified, over this project (see project memory) --
filling in full expected credit on every part reflects that, not an
assumption of partial completion.
"""
import sys, os
sys.path.insert(0, os.path.dirname(__file__))
from atoms import R

OUT_PAGES = os.path.join(os.path.dirname(__file__), '..', 'pages')
SZ = 12.96

# column x-spans read directly off rules400.tex's own \RECT grid lines
COL_PART = [
    (115.10, 143.78),  # (i)
    (144.26, 172.82),  # (ii)
    (173.30, 202.00),  # (iii)
    (202.49, 231.17),  # (iv)
]
COL_EXPECTED = (393.67, 461.25)

# row baseline y -- reusing the exact y already used by that row's own
# "1a"/"1b"/.../"Total" label in page400.tex, so fills sit on the same
# baseline as the printed row labels.
ROW_Y = {
    '1a': 437.00, '1b': 454.90, '1c': 472.80,
    '2a': 508.60, '2b': 526.50, '2c': 544.40,
    '3a': 580.20, '3b': 598.10, '3c': 616.10,
    'Total': 651.80,
}

# (row, [part-column point values], expected-total)
ROWS = [
    ('1a', [3, 3], 6),
    ('1b', [3, 3], 6),
    ('1c', [1, 1, 1, 2], 5),
    ('2a', [6], 6),
    ('2b', [6], 6),
    ('2c', [5], 5),
    ('3a', [2, 4], 6),
    ('3b', [6], 6),
    ('3c', [1, 1, 1, 2], 5),
]


def centered(text, x0, x1, y, sz=SZ):
    a = R(text, sz)
    cx = x0 + (x1 - x0 - a.w) / 2
    return a.emit(cx, y)


lines = []
grand_total = 0
for row, parts, expected in ROWS:
    y = ROW_Y[row]
    for val, (cx0, cx1) in zip(parts, COL_PART):
        lines += centered(str(val), cx0, cx1, y)
    lines += centered(str(expected), COL_EXPECTED[0], COL_EXPECTED[1], y)
    grand_total += expected

lines += centered(str(grand_total), COL_EXPECTED[0], COL_EXPECTED[1], ROW_Y['Total'])

with open(os.path.join(OUT_PAGES, 'answers400.tex'), 'w', encoding='utf-8') as f:
    f.write('%% ===== answers400.tex — generated by gen_400.py =====\n')
    f.write('\n'.join(lines) + '\n')
print(f"wrote pages/answers400.tex ({len(lines)} lines); grand total = {grand_total}")
