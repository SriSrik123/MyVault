term2 = HB(R("(", SZ), frac, R(")", SZ), Kern(2.0),
           R("(", SZ), R(N, SZ), sup(R("(5)", SZ), R(N, SZ)), R(")", SZ))
out = term1.emit(x0, 623.38)
cx = x0 + term1.w + 2.0
out += plus.emit(cx, 623.38)
cx += plus.w + 2.0
out += term2.emit(cx, 623.38)
