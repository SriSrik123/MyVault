#!/usr/bin/env python3
"""1b: second-order recurrence solves (p407 distinct-root b,c case; p410
repeated-root a,c case). a=1,b=9,c=5 (gen_402.py). R0=1,R1=2 fixed (printed,
same for every student).

Math (verified by hand, see project memory), citing Induction and Recursion
Notes p.24-26 formulas 11/21 directly per that page's own "you may use
formulas 11 and 21 on exams":
  (i)  x^2-(b+c)x+(bc)=0 = (x-b)(x-c) -> roots {b,c}={9,5}, distinct.
       r=(b+c)/2=7, s=|b-c|/2=2 -> r-s=5, r+s=9.
       k1=(1/2s)(R0(r+s)-R1)=(1/4)(9-2)=7/4; k2=(1/2s)(R1-R0(r-s))=(1/4)(2-5)=-3/4
       rho(n) = (7/4)(5)^n - (3/4)(9)^n
  (ii) (a^2)x^2-(2ac)x+(c^2)=0 = (ax-c)^2 -> repeated root r=c/a=5/1=5.
       k1=R0=1; k2=(R1-rR0)/r=(2-5)/5=-3/5
       rho(n) = (1)(5)^n + (-3/5)(n(5)^n)
Both verified n=0,1 against R0,R1 by hand.

Coordinates read directly off gen2.py's own pages/page407.tex / page410.tex."""
import sys, os
sys.path.insert(0, os.path.dirname(__file__))
from atoms import R, sup, Frac, HB, Kern

OUT_PAGES = os.path.join(os.path.dirname(__file__), '..', 'pages')
SZ = 14.04
M = "−"  # U+2212 minus, used inside parens for negative fills
N = "\U0001D45B"  # math-italic n -- plain ASCII 'n' is NOT in the font subset


def fit_centered(text, x0, x1, y, max_sz=SZ, min_sz=7.0, inset=1.0):
    """x0,x1 are the printed '(' and ')' glyphs' own origins (pen
    positions), NOT their ink edges -- the '(' glyph's ink extends
    rightward from x0 by its own width, so the real blank interior is
    [x0+paren_w, x1], not [x0,x1]. Missing this the first time around
    caused real overlap (e.g. '(45)' -- verified by zooming the render,
    not just trusting the coordinates on paper)."""
    paren_w = R("(", max_sz).w
    ix0, ix1 = x0 + paren_w, x1
    avail = (ix1 - ix0) - 2 * inset
    sz = max_sz
    while sz > min_sz and R(text, sz).w > avail:
        sz -= 0.5
    a = R(text, sz)
    cx = ix0 + (ix1 - ix0 - a.w) / 2
    return a.emit(cx, y)


# ============================================================== page 407
lines = []

# My problem line 1 (y=348.53/348.77): (rho(n+2)) - ((9)+(5))(rho(n+1)) + ((9)(5))(rho(n)) = 0
lines += fit_centered("9", 205.49, 224.21, 348.53)
lines += fit_centered("5", 246.65, 265.37, 348.53)
lines += fit_centered("9", 376.63, 395.47, 348.53)
lines += fit_centered("5", 401.0, 419.95, 348.53)

# My problem line 2, monic form (y=456.39/457.39):
# (1)(rho(n+2)) + (-14)(rho(n+1)) + (45)(rho(n)) = 0
lines += fit_centered("1", 135.62, 157.10, 456.91)
lines += fit_centered(f"({M}14)", 260.21, 281.69, 456.91, max_sz=11.0)
lines += fit_centered("45", 378.67, 397.39, 456.43)

# My solution (y=637.66, after the printed '='): (7/4)(5)^n - (3/4)(9)^n
x0 = 108.02 + R("=", SZ).w + 8.0
term1 = HB(R("(", SZ), Frac(R("7", SZ), R("4", SZ), sz=SZ), R(")", SZ),
           Kern(2.0), sup(R("(5)", SZ), R(N, SZ)))
minus = R(f" {M} ", SZ)
term2 = HB(R("(", SZ), Frac(R("3", SZ), R("4", SZ), sz=SZ), R(")", SZ),
           Kern(2.0), sup(R("(9)", SZ), R(N, SZ)))
out = term1.emit(x0, 637.66)
cx = x0 + term1.w + 2.0
out += minus.emit(cx, 637.66)
cx += minus.w + 2.0
out += term2.emit(cx, 637.66)
lines += out

with open(os.path.join(OUT_PAGES, 'answers407.tex'), 'w', encoding='utf-8') as f:
    f.write('%% ===== answers407.tex — generated by gen_1b.py =====\n')
    f.write('\n'.join(lines) + '\n')
print(f"wrote pages/answers407.tex ({len(lines)} lines)")

# ============================================================== page 410
lines = []

# My problem line 1 (y=334.13ish): (1)^2(rho(n+2)) - 2(1)(5)(rho(n+1)) + (5)^2(rho(n)) = 0
lines += fit_centered("1", 103.10, 121.82, 334.13)
lines += fit_centered("1", 250.37, 269.09, 334.13)
# second blank's own '(' is the second half of the merged ')(' run at
# 269.09 (measured: paren_w=5.83, so its own origin is 269.09+5.83=274.92)
lines += fit_centered("5", 269.09 + R("(", SZ).w, 293.57, 334.13)
lines += fit_centered("5", 404.83, 423.67, 334.13)

# My problem line 2, monic form (y≈441.99/442.15/443.11):
# (1)(rho(n+2)) + (-10)(rho(n+1)) + (25)(rho(n)) = 0
lines += fit_centered("1", 122.18, 143.66, 442.63)
lines += fit_centered(f"({M}10)", 246.77, 295.13, 442.63, max_sz=11.0)
lines += fit_centered("25", 392.11, 410.83, 442.15)

# My solution (y=623.38, after '='): (1)(5)^n + (-3/5)(n(5)^n)
x0 = 108.02 + R("=", SZ).w + 8.0
