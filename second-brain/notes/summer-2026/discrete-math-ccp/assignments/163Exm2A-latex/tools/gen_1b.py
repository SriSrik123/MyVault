with open(os.path.join(OUT_PAGES, 'answers410.tex'), 'w', encoding='utf-8') as f:
    f.write('%% ===== answers410.tex — generated by gen_1b.py =====\n')
    f.write('\n'.join(lines) + '\n')
print(f"wrote pages/answers410.tex ({len(lines)} lines)")
