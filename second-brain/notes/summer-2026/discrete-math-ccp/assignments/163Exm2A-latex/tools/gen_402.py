#!/usr/bin/env python3
"""Generate answers402.tex -- the J-number/a/b/c/d setup that every other
2A problem depends on. J-number reused from the 1C precedent (Sri's fixed
personal ID, confirmed 2026-07-25, not per-exam-random). Coordinates read
directly off tools/gen2.py's own output for pages/page402.tex.

a := mnm of the NONZERO J-digits, b := mxm of ALL J-digits (styleguide
Rules.md "Counting, Recurrence..." section); c := floor((b+a)/2) with the
halfway-decomposition chain (styleguide.md 5.7); d := smallest odd number
strictly greater than c (5.8, bare numeral, no work sheet)."""
import sys, os
sys.path.insert(0, os.path.dirname(__file__))
from atoms import R, Frac, Chain

SZ = 12.96
OUT_PAGES = os.path.join(os.path.dirname(__file__), '..', 'pages')

J = [0, 0, 4, 9, 9, 3, 1, 7]
a_val = min(v for v in J if v != 0)      # 1
b_val = max(J)                           # 9
c_val = (b_val + a_val) // 2             # 5 (evenly -- 10/2, no remainder)
assert (b_val + a_val) % 2 == 0
d_val = c_val + 1 if c_val % 2 == 0 else c_val + 2   # smallest odd > c; c=5 odd -> 7
d_val = c_val + 2 if c_val % 2 == 1 else c_val + 1
assert d_val == 7

lines = []
# J-number on the underline (A1) -- baseline on the printed line, same y
lines += R("00499317", 12).emit(372, 195.10)
# a := mnm{...} = 1
lines += R(str(a_val), SZ).emit(370, 245.54)
# b := mxm(...) = 9
lines += R(str(b_val), SZ).emit(250, 315.89)

# c := floor((b+a)/2) = floor((9+1)/2) = floor(10/2) = floor(5) = 5
# four fills after the printed floor(  (b+a)/2  ) expression, at the four
# printed '=' positions (180.02, 252.05, 324.07, 396.07); the fifth printed
# '=' (468.10) is left unused -- an exact (non-fractional) division has no
# halfway-decomposition step to show, per 5.7's own "adds no information
# but is the format" rule: here there IS no such intermediate to add.
FRACSZ = 12.96


def floor_of(inner_atom, y_center):
    """floor(  inner  ) as a single HB-emittable unit via direct \\TDEL
    calls (atoms.py's glyph-ladder Delim only knows ( ) { } -- floor/ceil
    route through math-mode \\lfloor \\rfloor like gen2.py's printed-page
    fix). Returns (tex_lines, total_width)."""
    h = inner_atom.ht + inner_atom.dp + 2.0
    half = h / 2
    lines_ = [f"\\TDEL{{__X__}}{{{y_center:.2f}}}{{{FRACSZ:g}}}"
              f"{{{half:.2f}}}{{{half:.2f}}}{{\\lfloor}}"]
    return lines_, inner_atom.w + 10.0, h


def emit_floor(x, y_baseline, inner_atom):
    """Place floor(inner) -- BOTH brackets closed (unlike the printed
    template's deliberately-open left-only lfloor, every answer step here
    is a complete, closed floor expression, per styleguide 5.7)."""
    h = inner_atom.ht + inner_atom.dp + 2.0
    half = h / 2
    yc = y_baseline - (inner_atom.ht - inner_atom.dp) / 2
    out = [f"\\TDEL{{{x:.2f}}}{{{yc:.2f}}}{{{FRACSZ:g}}}"
           f"{{{half:.2f}}}{{{half:.2f}}}{{\\lfloor}}"]
    out += inner_atom.emit(x + 9.0, y_baseline)
    xr = x + 9.0 + inner_atom.w + 3.0
    out.append(f"\\TDEL{{{xr:.2f}}}{{{yc:.2f}}}{{{FRACSZ:g}}}"
               f"{{{half:.2f}}}{{{half:.2f}}}{{\\rfloor}}")
    return out, xr + 9.0


# step 1: floor((9+1)/2)  -- at x=180.02+gap
frac1 = Frac(R(f"{b_val}+{a_val}", FRACSZ), R("2", FRACSZ), sz=FRACSZ)
out, _ = emit_floor(196, 375.53, frac1)
lines += out

# step 2: floor(10/2)
frac2 = Frac(R(str(b_val + a_val), FRACSZ), R("2", FRACSZ), sz=FRACSZ)
out, _ = emit_floor(268, 375.53, frac2)
lines += out

# step 3: floor(5)  -- (b+a)/2 divides evenly, so this is the collapsed
# integer already, one step earlier than the fractional-case template
inner3 = R(str(c_val), FRACSZ)
out, _ = emit_floor(340, 375.53, inner3)
lines += out

# step 4: bare numeral answer
lines += R(str(c_val), SZ).emit(412, 375.53)

# d := the smallest odd number strictly greater than c = 7
lines += R(str(d_val), SZ).emit(450, 433.27)

with open(os.path.join(OUT_PAGES, 'answers402.tex'), 'w') as f:
    f.write('%% ===== answers402.tex — generated by gen_402.py =====\n')
    f.write('\n'.join(lines) + '\n')
print(f"wrote pages/answers402.tex ({len(lines)} lines)")
print("J:", J, "a:", a_val, "b:", b_val, "c:", c_val, "d:", d_val)
