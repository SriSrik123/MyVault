#!/usr/bin/env python3
"""3b: Rtl((abcd)^(1/(abcd+1))) irrationality problem (p426). a=1,b=9,c=5,d=7.
abcd=315, abcd+1=316.

Page 426's own instruction is "Start proof on this side and continue on
pages that follow" -- i.e. only the two "My Problem:" substitution lines
belong on the printed page; the actual Rtl contradiction proof (styleguide
6.6) goes on work sheets, which -- like every other problem this session --
are deferred (see project memory). This script only fills the two
substitution lines."""
import sys, os
sys.path.insert(0, os.path.dirname(__file__))
from atoms import R

OUT_PAGES = os.path.join(os.path.dirname(__file__), '..', 'pages')


def fit_centered(text, x0, x1, y, max_sz, min_sz=4.0, inset=0.5):
    paren_w = R("(", max_sz).w
    ix0, ix1 = x0 + paren_w, x1
    avail = (ix1 - ix0) - 2 * inset
    sz = max_sz
    while sz > min_sz and R(text, sz).w > avail:
        sz -= 0.25
    a = R(text, sz)
    cx = ix0 + (ix1 - ix0 - a.w) / 2
    return a.emit(cx, y)


lines = []
vals = ["1", "9", "5", "7"]  # a, b, c, d, positional

# ---- line 1 (y~218/215/204.5): full positional Rtl((a)(b)(c)(d))^(1/((a)(b)(c)(d)+1))
base_spans = [(244.61, 269.21), (269.21, 293.69), (293.69, 318.17), (318.17, 342.67)]
for v, (x0, x1) in zip(vals, base_spans):
    lines += fit_centered(v, x0, x1, 218.54, 14.04)

denom_spans = [(354.31, 364.99), (364.99, 379.03), (379.03, 392.95), (392.95, 406.99)]
for v, (x0, x1) in zip(vals, denom_spans):
    lines += fit_centered(v, x0, x1, 215.06, 8.04)

# ---- line 2 (y~261/258/247.6): simplified Rtl((315)^(1/(316)))
lines += fit_centered("315", 244.61, 263.45, 261.17, 14.04)
lines += fit_centered("316", 269.21, 279.89, 258.17, 8.04)

with open(os.path.join(OUT_PAGES, 'answers426.tex'), 'w', encoding='utf-8') as f:
    f.write('%% ===== answers426.tex — generated by gen_3b.py =====\n')
    f.write('\n'.join(lines) + '\n')
print(f"wrote pages/answers426.tex ({len(lines)} lines)")
