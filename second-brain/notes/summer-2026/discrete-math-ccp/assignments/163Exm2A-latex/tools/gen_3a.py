#!/usr/bin/env python3
"""3a: phi(0):=c, phi(n+1):=phi(n)b+d recurrence + conjecture + induction
proof, all on the printed page (p424 -- unlike 1a/1b/2a/2b, this page
leaves dedicated room for the FULL proof, not deferred to a work sheet).
b=9,c=5,d=7.

Math (verified programmatically against direct unroll, matches this
project's very first hand-derivation of this exact recurrence from earlier
in the session): phi(0..3)=5,52,475,4282.
  Conjecture: forall n in N, phi(n) = (5)(9)^n + (7)((9^n-1)/8)
  Induction proof (SPf/BC/RcS/EPf per Induction and Recursion Notes'
  own template, e.g. its arithmetic/geometric progression proofs):
    BC: LS=phi(0)=5, RS=(5)(1)+(7)(0/8)=5. LS=RS.
    RcS: LS=phi(n+1)=phi(n)(9)+7
                     =((5)(9^n)+(7)((9^n-1)/8))(9)+7      [IH]
                     =(5)(9^(n+1))+(63)((9^n-1)/8)+7
                     =(5)(9^(n+1))+(7)((9^(n+1)-1)/8) = RS
  verified algebraically by hand and re-checked here."""
import sys, os
sys.path.insert(0, os.path.dirname(__file__))
from atoms import R, HB, VC, Kern, Frac, sup, Rule, cdots

OUT_PAGES = os.path.join(os.path.dirname(__file__), '..', 'pages')
M = "−"
N = "\U0001D45B"
PHI = "\U0001D711"  # math-italic phi


def fit_centered(text, x0, x1, y, max_sz, min_sz=6.0, inset=1.0):
    paren_w = R("(", max_sz).w
    ix0, ix1 = x0 + paren_w, x1
    avail = (ix1 - ix0) - 2 * inset
    sz = max_sz
    while sz > min_sz and R(text, sz).w > avail:
        sz -= 0.5
    a = R(text, sz)
    cx = ix0 + (ix1 - ix0 - a.w) / 2
    return a.emit(cx, y)


def closed_form_atom(sz):
    """(5)(9)^n + (7)((9^n-1)/8)"""
    t1 = HB(R("(5)", sz), Kern(1), sup(R("(9)", sz), R(N, sz)))
    num = HB(sup(R("9", sz), R(N, sz)), R(f" {M} 1", sz))
    t2 = HB(R("(7)", sz), Kern(1), R("(", sz), Frac(num, R("8", sz), sz=sz), R(")", sz))
    return HB(t1, Kern(3), R("+", sz), Kern(3), t2)


def bar_row(*atoms_, sz, gap=4.0):
    return HB(*atoms_, sep=gap) if len(atoms_) > 1 else atoms_[0]


lines = []

# rewrite line 1: phi(0):=(5)
lines += fit_centered("5", 326.95, 345.79, 265.13, 14.04)
# rewrite line 2: phi(n+1):=phi(n)(9)+(7)
lines += fit_centered("9", 375.79, 394.51, 284.45, 14.04)
lines += fit_centered("7", 416.83, 435.67, 284.45, 14.04)

# conjecture (y=395.33, after printed '=')
SZ = 11.0
cf = closed_form_atom(SZ)
cx0 = 285.05 + R("=", 14.04).w + 6
lines += cf.emit(cx0, 395.33)

with open(os.path.join(OUT_PAGES, 'answers424.tex'), 'w', encoding='utf-8') as f:
    f.write('%% ===== answers424.tex — generated by gen_3a.py =====\n')
    f.write('\n'.join(lines) + '\n')
print(f"wrote pages/answers424.tex ({len(lines)} lines)")

# ---- induction proof, 4(i): ALL of it on p425, not split with p424
# (2026-08-02, Sri: "all of 3a on the next page and don't have continued")
# -- p424 now stops at the conjecture, matching every other "prove by
# induction"/"show work that follows" page in this exam (2c's proof is
# entirely on 421/422, nothing on the problem statement's own page
# either). p425 is entirely blank on the original exam and has plenty of
# room for the whole SPf..EPf proof (previously split only because an
# earlier, smaller font size fit part of it on 424 -- no longer true once
# PSZ grew for legibility, and no longer the point now that the whole
# proof moves off 424 regardless of whether it WOULD fit there).
# Rows vary hugely in vertical extent (a plain text label vs. a row with a
# stacked fraction AND a superscript) -- a fixed rowgap caused real,
# confirmed overlap wherever a tall row was followed immediately by the
# next one (fraction ink running into the row below; the 'Hence' VC block,
# 3 rows tall internally, got only one rowgap's worth of clearance before
# the next element). Advance y by each row's own actual depth (below
# baseline) plus a fixed pad, not a uniform constant.
#
# PSZ bumped 7.3->9.5 (audit finding, 2026-08-01: Sri read the built page
# and found the proof illegible -- same "font too small" class as 1c/2c).
# The size bump also exposed that the original look-BACK-only emit_row
# (advance by the CURRENT row's depth) never accounted for a row whose own
# HEIGHT is unusually tall -- step4 stacks a superscript directly above
# its own Frac(), so its ht is much taller than a plain text row, and the
# manual "y += 1.8" fudge before it (guessed, not measured) stopped being
# enough once every row grew ~30% taller. Confirmed by render: "n+8"/"3"
# visibly overlapping into the row above. Fixed at the root instead of
# re-guessing a bigger fudge factor: emit_row now measures each row's own
# excess height (over a normal single-line row at this size) and adds
# clearance BEFORE placing it, so any future unusually-tall row is safe
# automatically, not just this one.
PSZ = 9.5
x0 = 90.0
y = 100.0
rowgap = 9.5
PAD = 3.0
NORMAL_HT = R("=", PSZ).ht


def emit_row(atom, x=x0):
    global y
    y += max(0.0, atom.ht - NORMAL_HT)
    out = atom.emit(x, y)
    y += max(rowgap, atom.dp + PAD + 3.0)
    return out


def emit_rule(w, x=x0):
    global y
    out = [f"\\DLINE{{{x:.2f}}}{{{y:.2f}}}{{{x+w:.2f}}}{{{y:.2f}}}{{0.55}}"]
    y += rowgap
    return out


lines = []

# SPf + P(n) definition -- proof labels (SPf/BC/RcS/LS/RS/EPf) are text,
# not math-italic content: font='b'/'bb' (Book Antiqua), not the Cambria
# default -- Cambria's subset has no plain latin letters at all (same
# "only math-italic + a curated symbol set" rule as the 1C project found).
# ':=' also avoided -- plain ':' (U+003A) isn't in the subset either;
# '≔' (already used successfully elsewhere as the assignment symbol)
# sidesteps it rather than fighting a second missing-glyph case.
lines += emit_row(R("SPf", PSZ, font='b'))
pn_def = HB(R(f"𝑃({N})", PSZ), R("≔", PSZ), R(f"({PHI}(", PSZ), R(N, PSZ), R(")=", PSZ),
            closed_form_atom(PSZ), R(")", PSZ))
lines += emit_row(pn_def)
y += 1

# BC block
lines += emit_row(R("BC", PSZ, font='bb'))
ls_bc = HB(R("LS", PSZ, font='b'), Kern(10), R("=", PSZ), Kern(4), R(f"{PHI}(0)", PSZ), Kern(4), R("=", PSZ), Kern(4), R("5", PSZ))
lines += emit_row(ls_bc)
rs_bc = HB(R("RS", PSZ, font='b'), Kern(10), R("=", PSZ), Kern(4),
           R("(5)(1)", PSZ), Kern(2), R("+", PSZ), Kern(2),
           R("(7)", PSZ), Kern(1), R("(", PSZ), Frac(R("0", PSZ), R("8", PSZ), sz=PSZ), R(")", PSZ),
           Kern(4), R("=", PSZ), Kern(4), R("5", PSZ))
lines += emit_row(rs_bc)
lines += emit_row(HB(R("LS", PSZ, font='b'), R(" = ", PSZ, font='b'), R("RS", PSZ, font='b')))
lines += emit_rule(80)
lines += emit_row(R("𝑃(0)", PSZ))

# RcS block
lines += emit_row(R("RcS", PSZ, font='bb'))
hyp = HB(R("𝑃(0) 𝑃(1) ", PSZ), cdots(PSZ), Kern(2), R(f" 𝑃({N})", PSZ))
lines += emit_row(hyp)
lines += emit_rule(160)
lines += emit_row(R("LS", PSZ, font='b'))
lines += emit_row(HB(R("=", PSZ), Kern(4), R(f"{PHI}({N}+1)", PSZ)))
step2 = HB(R("=", PSZ), Kern(4), R(f"{PHI}({N})(9)+7", PSZ))
lines += emit_row(step2)
step3 = HB(R("=", PSZ), Kern(4), R("(", PSZ), closed_form_atom(PSZ), R(")(9)+7", PSZ))
lines += emit_row(step3)
step4num = HB(sup(R("9", PSZ), HB(R(N, PSZ), R("+1", PSZ))), R(f" {M} 1", PSZ))
step4 = HB(R("=", PSZ), Kern(4), R("(5)", PSZ), Kern(1),
           sup(R("(9)", PSZ), HB(R(N, PSZ), R("+1", PSZ))), Kern(3), R("+", PSZ), Kern(3),
           R("(63)", PSZ), Kern(1), R("(", PSZ), Frac(HB(sup(R("9", PSZ), R(N, PSZ)), R(f" {M} 1", PSZ)), R("8", PSZ), sz=PSZ), R(")", PSZ),
           Kern(3), R("+7", PSZ))
lines += emit_row(step4)
step5 = HB(R("=", PSZ), Kern(4), R("(5)", PSZ), Kern(1),
           sup(R("(9)", PSZ), HB(R(N, PSZ), R("+1", PSZ))), Kern(3), R("+", PSZ), Kern(3),
           R("(7)", PSZ), Kern(1), R("(", PSZ), Frac(step4num, R("8", PSZ), sz=PSZ), R(")", PSZ))
lines += emit_row(step5)
lines += emit_row(HB(R("=", PSZ), Kern(4), R("RS", PSZ, font='b')))
lines += emit_rule(80)
lines += emit_row(R(f"𝑃({N}+1)", PSZ))
y += 1

# Hence -- simplified to a plain vertical stack (P(0), then the RcS
# hypothesis-implies-conclusion pair, then the final bar+conclusion)
# rather than the notes' side-by-side P(0)-beside-a-fraction-box layout:
# HB+VC alignment for that specific shape kept mis-placing "P(0)" relative
# to the box: same math content, small format simplification.
lines += emit_row(R("𝑃(0),", PSZ))
hyp2 = HB(R("𝑃(0) 𝑃(1) ", PSZ), cdots(PSZ), Kern(2), R(f" 𝑃({N})", PSZ))
lines += emit_row(hyp2)
lines += emit_rule(140)
lines += emit_row(R(f"𝑃({N}+1)", PSZ))
lines += emit_rule(280)
lines += emit_row(R(f"∀{N}∈ℕ(𝑃({N}))", PSZ))
lines += emit_row(R("EPf", PSZ, font='b'))

with open(os.path.join(OUT_PAGES, 'answers425.tex'), 'w', encoding='utf-8') as f:
    f.write('%% ===== answers425.tex — generated by gen_3a.py =====\n')
    f.write('\n'.join(lines) + '\n')
print(f"wrote pages/answers425.tex ({len(lines)} lines), final y={y:.1f} (limit ~714)")
