N = "\U0001D45B"


def fit_centered(text, x0, x1, y, max_sz=SZ, min_sz=6.0, inset=1.0):
    paren_w = R("(", max_sz).w
    ix0, ix1 = x0 + paren_w, x1
    avail = (ix1 - ix0) - 2 * inset
    sz = max_sz
    while sz > min_sz and R(text, sz).w > avail:
        sz -= 0.5
    a = R(text, sz)
    cx = ix0 + (ix1 - ix0 - a.w) / 2
    return a.emit(cx, y)


class FloorAtom(Atom):
    """floor(inner), both brackets, via direct \\TDEL (atoms.py's Delim
    ladder only knows ( ) { } -- see gen_402.py's identical workaround)."""
    def __init__(self, inner, sz):
        self.inner, self.sz = inner, sz
        pad = 1.0
        self.ht = inner.ht + pad
        self.dp = inner.dp + pad
        self.gap = 3.0
        self.w = self.gap + inner.w + self.gap

    def emit(self, x, y):
        h = self.ht + self.dp
        half = h / 2
        yc = y - (self.ht - self.dp) / 2
        out = [f"\\TDEL{{{fmt(x)}}}{{{fmt(yc)}}}{{{self.sz:g}}}"
               f"{{{fmt(half)}}}{{{fmt(half)}}}{{\\lfloor}}"]
        out += self.inner.emit(x + self.gap, y)
        xr = x + self.gap + self.inner.w + self.gap
        out.append(f"\\TDEL{{{fmt(xr)}}}{{{fmt(yc)}}}{{{self.sz:g}}}"
                   f"{{{fmt(half)}}}{{{fmt(half)}}}{{\\rfloor}}")
        return out


def closed_form(v0, v1, ratio, inc, denom, sz=CSZ):
    """(ratio)^floor(n/2) [ (v0)((1+(-1)^n)/2) + (v1)((1+(-1)^(n+1))/2) ]
       + (inc)((ratio^floor(n/2)-1)/denom)"""
    floor_n2 = FloorAtom(Frac(R(N, sz), R("2", sz), sz=sz), sz)
    pw = sup(R(f"({ratio})", sz), floor_n2)

    m1 = R(f"({M}1)", sz)
    par1 = Frac(HB(R("1+", sz), sup(m1, R(N, sz))), R("2", sz), sz=sz)
    par2 = Frac(HB(R("1+", sz), sup(m1, R(f"{N}+1", sz))), R("2", sz), sz=sz)
    # plain (non-tall) outer parens, not wrap(): the tall \TDEL assembly
    # construction at this height/size combination renders with visibly
    # misaligned/gapped pieces (confirmed by render -- looked like stray
    # readable text where a closing paren should be, reproducibly, only
    # past a certain height/size ratio). A slightly-too-short plain paren
    # around 2-row content is a minor cosmetic gap; a broken assembly
    # glyph that reads as bogus text is a real defect. Chose correctness.
    bracket = HB(R("(", sz), R(f"({v0})", sz), Kern(2), R("(", sz), par1, R(")", sz),
                 Kern(3), R("+", sz), Kern(3),
                 R(f"({v1})", sz), Kern(2), R("(", sz), par2, R(")", sz), R(")", sz))
    part1 = HB(pw, Kern(2), bracket)

    floor_n2b = FloorAtom(Frac(R(N, sz), R("2", sz), sz=sz), sz)
    pw2 = sup(R(f"({ratio})", sz), floor_n2b)
    num2 = HB(pw2, R(f" {M} 1", sz))
    frac2 = Frac(num2, R(str(denom), sz), sz=sz)
    part2 = HB(R(f"({inc})", sz), Kern(2), R("(", sz), frac2, R(")", sz))

    return HB(part1, Kern(4), R("+", sz), Kern(4), part2)


