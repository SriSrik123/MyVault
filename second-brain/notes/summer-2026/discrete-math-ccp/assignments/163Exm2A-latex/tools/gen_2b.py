#!/usr/bin/env python3
"""2b: Sm(alpha,n)/Sm(phi,n) geometric-sum conjectures (p419). a=1,b=9,c=5,d=7.

Math (verified programmatically against direct summation for n=0..5, see
project memory): splitting alpha(n)/phi(n) (from 2a) into even/odd-index
sub-sequences, each itself a simple ratio-63 geometric-plus-constant
sequence, then summing each geometric sub-sum in closed form:
  Sm(alpha,n) = (71/62)((63^(floor(n/2)+1)-1)/62)
              + (3357/62)((63^(floor((n-1)/2)+1)-1)/62) - (9/62)(n+1)
  Sm(phi,n)   = (373/62)((63^(floor(n/2)+1)-1)/62)
              + (497/62)((63^(floor((n-1)/2)+1)-1)/62) - (1/62)(n+1)
where the coefficients are v0+inc/(ratio-1) (even branch) and
v1+inc/(ratio-1) (odd branch), ratio=63, inc=9 (alpha) or 1 (phi).
Matches the exact template shape read off the solved exhibit for this
problem type (own ratio=35, but identical structure)."""
import sys, os
sys.path.insert(0, os.path.dirname(__file__))
from atoms import R, HB, Kern, Frac, sup, Atom, fmt

OUT_PAGES = os.path.join(os.path.dirname(__file__), '..', 'pages')
SZ = 12.96
CSZ = 8.0  # even more terms than 2a's closed form -- start small
M = "−"
N = "\U0001D45B"


def fit_centered(text, x0, x1, y, max_sz=SZ, min_sz=6.0, inset=1.0):
    paren_w = R("(", max_sz).w
    ix0, ix1 = x0 + paren_w, x1
    avail = (ix1 - ix0) - 2 * inset
    sz = max_sz
    while sz > min_sz and R(text, sz).w > avail:
        sz -= 0.5
    a = R(text, sz)
    cx = ix0 + (ix1 - ix0 - a.w) / 2
    return a.emit(cx, y)


class FloorAtom(Atom):
    """floor(inner) via direct \\TDEL -- atoms.py's Delim ladder only knows
    ( ) { }; see gen_402.py's original workaround."""
    def __init__(self, inner, sz):
        self.inner, self.sz = inner, sz
        pad = 1.0
        self.ht = inner.ht + pad
        self.dp = inner.dp + pad
        self.gap = 2.5
        self.w = self.gap + inner.w + self.gap

    def emit(self, x, y):
        h = self.ht + self.dp
        half = h / 2
        yc = y - (self.ht - self.dp) / 2
        out = [f"\\TDEL{{{fmt(x)}}}{{{fmt(yc)}}}{{{self.sz:g}}}"
               f"{{{fmt(half)}}}{{{fmt(half)}}}{{\\lfloor}}"]
        out += self.inner.emit(x + self.gap, y)
        xr = x + self.gap + self.inner.w + self.gap
        out.append(f"\\TDEL{{{fmt(xr)}}}{{{fmt(yc)}}}{{{self.sz:g}}}"
                   f"{{{fmt(half)}}}{{{fmt(half)}}}{{\\rfloor}}")
        return out


def sm_term(knum, kden, ratio, floor_extra, denom, sz):
    """(knum/kden)((ratio^(floor(...)+1)-1)/denom), floor_extra is '' (n/2)
    or '-1' ((n-1)/2). Plain (non-tall) parens throughout -- 2a lesson:
    wrap()'s tall-assembly rendering at small sizes is unreliable; a
    slightly-short plain paren around 2-row content is a minor cosmetic
    gap, not a real defect."""
    coef = Frac(R(str(knum), sz), R(str(kden), sz), sz=sz)
    floor_num = R(f"({N}{floor_extra})", sz) if floor_extra else R(N, sz)
    floor_inner = Frac(floor_num, R("2", sz), sz=sz)
    fl = FloorAtom(floor_inner, sz)
    exponent = HB(fl, R("+1", sz))
    power = sup(R(f"({ratio})", sz), exponent)
    num = HB(power, R(f" {M} 1", sz))
    inner_frac = Frac(num, R(str(denom), sz), sz=sz)
    return HB(R("(", sz), coef, R(")", sz), Kern(1.5),
              R("(", sz), R("(", sz), inner_frac, R(")", sz), R(")", sz))


def sm_formula(ke_num, ko_num, kden, ratio, denom, lin_num, lin_den, sz=CSZ):
    even_term = sm_term(ke_num, kden, ratio, "", denom, sz)
    odd_term = sm_term(ko_num, kden, ratio, f"{M}1", denom, sz)
    lin = HB(R("(", sz), Frac(R(str(lin_num), sz), R(str(lin_den), sz), sz=sz),
              R(")", sz), Kern(1.5), R("(", sz), R(f"{N}+1", sz), R(")", sz))
    return HB(even_term, Kern(3), R("+", sz), Kern(3), odd_term,
              Kern(3), R(f"{M}", sz), Kern(3), lin)


lines = []

# My problem line 1 (y~341.6): alpha(0):=(1)    phi(0):=alpha(0)+(5)=(1)+(5)
