#!/usr/bin/env python3
"""1c: construct a set S per target cardinality, using set operations
{complement, cup, cap, setminus, product, coproduct, Fnc(A,B), grouping,
~} (p411's own printed list). No solved exhibit exists for 1c in either
reference PDF (styleguide sec.8 #8 / project memory).

Scope (re-read from p411-415 directly): p411's four directives -- draw a
formation-tree, draw a second formation-tree for the constructed set, prove
the cardinality equals the target, write a word-problem -- are each
explicitly routed to "pages that follow, numbered as per instructions",
matching the treatment given to every other problem's derivation work in
this exam (1a/1b/2a/3b all defer their "show work" to unbuilt work sheets).
Only the "My expression:" line lives on the printed pages (412-415)
themselves -- that's what's filled here.

"Formation tree" = an operator/connective PARSE tree (Logic Notes pp.3-4,
19-20: "Basic Formation Trees", "on the very last exam you will need to
draw a formation tree") -- root=outermost connective, leaves=atoms -- NOT
the Sets/Counting Notes "Tree" (element-by-element enumeration), a
different, unrelated device that happens to share the word "tree". Noted
for whoever builds the deferred work-sheet trees later.

Only a:=nu(A), b:=nu(B) are pinned by p411 (the two given sets). c,d (i,
iii) and p,q,r,s (iv) are undefined on the page -- read as: the student
introduces more sets freely, same as A,B (an open construct-your-own-
example problem, unlike 3c where x/y's b,c ARE the exam's fixed global
values). Every answer stays purely symbolic (never substituting actual
sizes), honoring "you will get 0 if you calculate numerical values".

FONT CONSTRAINT (checked this exam's actual embedded cmap, not assumed):
CambriaM.ttf's math-italic CAPITAL letters are limited to A,B,F,J,P,R,S --
every other capital (C,D,Q,V,W,X,Y,Z,...) was never painted on the blank
exam and so never extracted; the subset symbol '⊆' is also entirely
absent. 'S' is p411's own name for the answer set, leaving only A,B,F,J,P,R
for content sets/results. Consequences, forced by the font, not style:
  - the two extra sets needed for (i)/(iii) are named F and J, not C,D --
    but their CARDINALITIES are still literally called c and d (lowercase
    c,d exist in the font, and p412/414 print lower-case c,d in the target
    formula, so that naming is fixed regardless of the sets' own letters).
  - part (iv) reuses p:=a, q:=b, r:=c, s:=d (i.e. reuses A,B,F,J) instead
    of introducing 4 more sets with no capitals left to name them.
  - part (iv)'s two binomial-sized pieces are described as "apply (iii)'s
    construction again with different target sizes" rather than spelled
    out as raw operator expressions a second time -- (iii) already needs
    a subset-of-size-k description in English (no bound-variable capital
    is left to write "{Y subset X | ...}" symbolically either), so a
    second independent from-scratch version would need yet more capitals
    the font doesn't have. Flagged rather than silently worked around.
  - "X contains Y" containment notes are stated in English (Book Antiqua
    prose), never with the unavailable '⊆' glyph.
"""
import sys, os
sys.path.insert(0, os.path.dirname(__file__))
from atoms import R, HB, VC, Kern, smart, fmt

OUT_PAGES = os.path.join(os.path.dirname(__file__), '..', 'pages')
SZ = 11.04
PSZ = SZ - 2.5


def bt(text, sz=PSZ):
    """English annotation run (Book Antiqua) -- kept strictly separate
    from math runs (default Cambria has no plain Latin letters at all)."""
    return R(text, sz, font='b')


def mt(text, sz=PSZ):
    return R(text, sz)


def write_page(folio, lines):
    path = os.path.join(OUT_PAGES, f'answers{folio}.tex')
    with open(path, 'w', encoding='utf-8') as f:
        f.write(f'%% ===== answers{folio}.tex — generated by gen_1c.py =====\n')
        f.write('\n'.join(lines) + '\n')
    print(f"wrote pages/answers{folio}.tex ({len(lines)} lines)")


# ---- (i) p412: (a+b)(c-d) ----
# S := (A co B) x (F \ J); F,J,{empty set} witnesses nu(F)=c, nu(J)=d,
# J subset F -- "inside"/"chosen with" replaced with a bare J\F={} identity
# (2026-08-02, Sri: "no words ... exactly like the solution exam"),
# equivalent to J subset F but spelled with only already-available symbols
# (no '⊆' glyph in this font -- see gen_1c.py's own cmap-gap docstring).
s1 = HB(R("𝑆 ≔ (𝐴∐𝐵)×(𝐹∖𝐽)", SZ), Kern(10),
        R("(𝜈(𝐹)=𝑐, 𝜈(𝐽)=𝑑, 𝐽∖𝐹={ })", SZ))
lines412 = s1.emit(144.02, 178.0)
write_page(412, lines412)

# ---- (ii) p413: (a+b)^(c+d) ----
s2 = R("𝑆 ≔ 𝐹𝑛𝑐(𝐹∐𝐽, 𝐴∐𝐵)", SZ)
lines413 = s2.emit(144.02, 205.0)
write_page(413, lines413)

# ---- (iii) p414: C(c+d, a-b) -- "subsets(size,source)" is the same
# functional-notation shorthand already used as this part's own FTree root
# label (gen_1c_work.py), reused here so the printed definition and the
# tree agree on one symbol instead of spelling it out in English.
s3 = smart("𝑆 ≔ subsets((𝑎−𝑏), 𝐹∐𝐽)", SZ)
lines414 = s3.emit(144.02, 189.0)
write_page(414, lines414)

# ---- (iv) p415: C( C(p+q,r+s), C(a-b,c-d) ) -- reuses p:=a,q:=b,r:=c,s:=d
# (so the two inner binomials are C(a+b,c+d) and C(a-b,c-d)), each built by
# reapplying (iii)'s subsets(size,source) construction with different sizes.
p_def = smart("𝑃 ≔ subsets((𝑐+𝑑), 𝐴∐𝐵)", PSZ)
r_def = smart("𝑅 ≔ subsets((𝑐−𝑑), 𝐴∖𝐵)   (𝐵∖𝐴={ })", PSZ)
s4_def = smart("𝑆 ≔ subsets(𝜈(𝑅), 𝑃)", PSZ)
block = VC([p_def, r_def, s4_def], sz=PSZ, gap=9.0)
lines415 = block.emit(144.02, 220.0)
write_page(415, lines415)
