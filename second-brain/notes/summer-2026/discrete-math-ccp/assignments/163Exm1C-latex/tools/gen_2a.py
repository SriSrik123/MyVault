#!/usr/bin/env python3
"""Generate answers310.tex + work sheet 3100 for problem 2a.
s=2, b=0 (positional My{s,b}={2,0} per confirmed decision); alphabet for
tree branching is {0,2} increasing."""
import sys, os
sys.path.insert(0, os.path.dirname(__file__))
from atoms import R, HB, Kern, Chain, Chevrons, assign, strike, fmt
from expr import SS, B_, Wrd, OM, RA
from tree import build, Tree
from pieces import lay_pieces, write_sheets

SZ = 11.04
OUT_PAGES = os.path.join(os.path.dirname(__file__), '..', 'pages')
OUT_SHEETS = os.path.join(os.path.dirname(__file__), '..', 'sheets')

s_val, b_val = 2, 0
alphabet = sorted([s_val, b_val])   # [0, 2], increasing for tree branching

# words with repetition allowed, order matters: every prefix is valid
top_i = build(3, alphabet, valid_prefix=lambda p: True)


def leaves_of(nodes, depth=3):
    """Real leaves are complete depth-digit words (no dashes/spaces left);
    a childless node that's still partial is a DEAD branch, not a word."""
    out = []
    for n in nodes:
        if not n.children:
            if '_' not in n.label and len(n.label) == depth:
                out.append(n.label)
        else:
            out += leaves_of(n.children, depth)
    return out
words_i = sorted(leaves_of(top_i), key=lambda s: [int(c) for c in s])

# order does not matter, repetition allowed: non-decreasing prefixes only
top_ii = build(3, alphabet, valid_prefix=lambda p: all(p[i] <= p[i+1] for i in range(len(p)-1)))
words_ii = sorted(leaves_of(top_ii), key=lambda s: [int(c) for c in s])

assert words_i == ['000', '002', '020', '022', '200', '202', '220', '222']
assert words_ii == ['000', '002', '022', '222']

# ---------------------------------------------------------------- {s,b}->{2,0}
sb_chain = Chain(
    R("{" + SS + "," + B_ + "}", SZ),
    [HB(R("({" + SS + "," + B_ + "})", SZ),
        Chevrons([assign(R(SS, SZ), R(str(s_val), SZ)), assign(R(B_, SZ), R(str(b_val), SZ))])),
     R(f"{{{s_val}, {b_val}}}", SZ)],
    sz=SZ)

tree_i = Tree(3, top_i, sz=10.0, col_w=46.0)
listing_i = R(f"{Wrd}(3,{{{s_val},{b_val}}},{OM},{RA}) = {{" + ", ".join(words_i) + "}", SZ)

tree_ii_title = HB(R(f"{Wrd}(3,{{{s_val},{b_val}}},", SZ), strike(R(OM, SZ)),
                    R(f",{RA}) = {{" + ", ".join(words_ii) + "}", SZ))
tree_ii = Tree(3, top_ii, sz=10.0, col_w=46.0)

pieces_all = [
    ("2a", sb_chain, 4, 10),
    ("2a.i.0", tree_i, 6, 10),
    ("2a.i.1", listing_i, 8, 10),
    ("2a.ii.0", tree_ii, 10, 10),
    ("2a.ii.1", tree_ii_title, 8, 8),
]
sheets = lay_pieces(pieces_all)
folios = write_sheets(3100, sheets, OUT_SHEETS)
print("2a work sheets used:", folios)

# ---------------------------------------------------------------- printed page 310
lines310 = []
lines310 += R(f"{s_val}, {b_val}", SZ).emit(255, 224.42)             # My{s,b}=
lines310 += R(f"{s_val},{b_val}", 10.0).emit(212, 338.81)            # 3(i) Wrd alphabet
row1 = ", ".join(words_i[:4]); row2 = ", ".join(words_i[4:])
lines310 += R(row1, 10.0).emit(410, 325.0)
lines310 += R(row2, 10.0).emit(410, 345.0)
lines310 += R(f"{s_val}, {b_val}", 10.0).emit(297, 456.91)           # 3(i) nu alphabet
lines310 += R("8", 21.96).emit(484, 456.91)
lines310 += R(f"{s_val},{b_val}", 10.0).emit(212, 607.27)            # 3(ii) Wrd alphabet
lines310 += R(", ".join(words_ii), 10.0).emit(410, 600.0)
lines310 += R(f"{s_val}, {b_val}", 10.0).emit(297, 727.42)           # 3(ii) nu alphabet
lines310 += R("4", 21.96).emit(484, 727.42)
with open(os.path.join(OUT_PAGES, 'answers310.tex'), 'w') as f:
    f.write('%% ===== answers310.tex — generated by gen_2a.py =====\n')
    f.write('\n'.join(lines310) + '\n')
print(f"wrote pages/answers310.tex ({len(lines310)} lines)")
