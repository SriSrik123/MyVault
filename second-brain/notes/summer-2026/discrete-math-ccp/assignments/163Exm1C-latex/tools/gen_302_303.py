#!/usr/bin/env python3
"""Generate answers302.tex + answers303.tex -- the J-number/SJ/MSJ/s/b setup
that EVERY other problem depends on. Format confirmed directly against
SOL-2024's own filled pages 302-303 (sol0_01.png/sol0_02.png): J-number as
an unbroken digit string on the underline (A1), each Ji filled after its
own '=', SJ/Lst(J) as plain comma lists in the printed brace/parens, MSJ as
value:multiplicity pairs increasing by value, s/b/nu(SJ)/nu(MSJ) as bare
numerals after their '='. This was the one page pair I'd missed entirely
in the first pass -- caught on the format-vs-sample re-audit."""
import sys, os
sys.path.insert(0, os.path.dirname(__file__))
from atoms import R

SZ = 12.96
OUT_PAGES = os.path.join(os.path.dirname(__file__), '..', 'pages')

J = [0, 0, 4, 9, 9, 3, 1, 7]
SJ = sorted(set(J))                 # [0,1,3,4,7,9]
nu_SJ = len(SJ)                     # 6
Lst_J = SJ                          # same values, as an ordered list
n_l = [J.count(v) for v in SJ]      # [2,1,1,1,1,2]
MSJ = list(zip(SJ, n_l))            # [(0,2),(1,1),(3,1),(4,1),(7,1),(9,2)]
nu_MSJ = sum(n_l)                   # 8
s_val = max(k for k in range(1, 9) if J[k - 1] == 0)          # 2
b_val = min(v for v in J if v % 2 == 0)                        # 0

# ---------------------------------------------------------------- page 302
lines302 = []
lines302 += R("00499317", SZ).emit(380, 177.62)                       # JN
j_eq_x = [122.54, 176.30, 226.97, 277.73, 331.51, 385.39, 439.18, 489.82]
for x, val in zip(j_eq_x, J):
    lines302 += R(str(val), SZ).emit(x + 8, 234.62)
lines302 += R(", ".join(str(v) for v in SJ), SZ).emit(404, 386.45)     # SJ={...}
lines302 += R(str(nu_SJ), SZ).emit(376, 432.05)                        # nu(SJ)=
lines302 += R(", ".join(str(v) for v in Lst_J), SZ).emit(416, 485.35)  # Lst(J)=(...)
msj_str = ", ".join(f"{v}:{m}" for v, m in MSJ)
lines302 += R(msj_str, SZ).emit(222, 719.62)                           # MSJ={...}
with open(os.path.join(OUT_PAGES, 'answers302.tex'), 'w') as f:
    f.write('%% ===== answers302.tex — generated by gen_302_303.py =====\n')
    f.write('\n'.join(lines302) + '\n')
print(f"wrote pages/answers302.tex ({len(lines302)} lines)")

# ---------------------------------------------------------------- page 303
lines303 = []
lines303 += R(str(nu_MSJ), SZ).emit(376, 86.66)     # nu(MSJ)=
lines303 += R(str(s_val), SZ).emit(376, 118.46)     # s:=...=
lines303 += R(str(b_val), SZ).emit(376, 174.62)     # b:=...=
with open(os.path.join(OUT_PAGES, 'answers303.tex'), 'w') as f:
    f.write('%% ===== answers303.tex — generated by gen_302_303.py =====\n')
    f.write('\n'.join(lines303) + '\n')
print(f"wrote pages/answers303.tex ({len(lines303)} lines)")

print("SJ:", SJ, "nu(SJ):", nu_SJ, "MSJ:", MSJ, "nu(MSJ):", nu_MSJ, "s:", s_val, "b:", b_val)
