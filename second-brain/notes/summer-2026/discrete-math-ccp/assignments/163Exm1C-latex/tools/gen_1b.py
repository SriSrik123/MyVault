SZ = 11.04
OUT_PAGES = os.path.join(os.path.dirname(__file__), '..', 'pages')
OUT_SHEETS = os.path.join(os.path.dirname(__file__), '..', 'sheets')

StJ = [0, 1, 3, 4, 7, 9]


def divides(a, b):
    return b == 0 if a == 0 else b % a == 0


F = [(x, y) for x in StJ for y in StJ if not divides(x, y)]
G = [(x, y) for x in StJ for y in StJ if not divides(y, x)]
assert len(F) == 20 and len(G) == 20


class Box(HB):
    """Zero-content wrapper so a fixed-size custom atom (DivTable, wrapped
    lines) can be dropped into an HB/VStack the same as any other Atom."""
    def __init__(self, atom):
        self.atom = atom
        self.w, self.ht, self.dp = atom.w, atom.ht, atom.dp

    def emit(self, x, y):
        return self.atom.emit(x, y)


class VStack:
    """Top-to-bottom LEFT-aligned stack of heterogeneous atoms (unlike VC,
    which centers). rows: list of (atom, gap_before)."""
    def __init__(self, rows):
        self.rows = rows
        self.w = max(a.w for a, _ in rows)
        ys, cy = [], 0.0
        first = True
        for a, gap in rows:
            if first:
                cy = a.ht
                first = False
            else:
                cy += gap + a.ht
            ys.append(cy)
            cy += a.dp
        self.ys = ys
        self.ht = rows[0][0].ht
        self.dp = ys[-1] + rows[-1][0].dp

    def emit(self, x, y):
        out = []
        for (a, _), ry in zip(self.rows, self.ys):
            out += a.emit(x, y + ry)
        return out


def wrap_listing(pairs, per_line, sz=SZ):
    """comma-separated '(x,y)' items, `per_line` items per row, left-aligned
    rows stacked -- returns a VStack-compatible atom."""
    lines = [pairs[i:i + per_line] for i in range(0, len(pairs), per_line)]
    rows = []
    for i, line in enumerate(lines):
        text = ", ".join(f"({x},{y})" for x, y in line) + ("," if i < len(lines) - 1 else "")
        rows.append((R(text, sz), 6.0))
    return VStack(rows)


def bracket_line(atom, sz=SZ):
    return wrap(atom, l='{', r='}', sz=sz)


def gen_piece(label, rel_sym, table_pairs, letter):
    defline = R(f"{letter} ≔ {{({X_},{Y_}) ∈ ({St_J})×({St_J}) | {rel_sym}}}", SZ)
    table = Box(DivTable(StJ, StJ, table_pairs, f"({X_},{Y_})", sz=9.5,
                          cell_w=40, cell_h=22, label_w=30))
    concl = bracket_line(wrap_listing(table_pairs, 10, sz=SZ), sz=SZ)
    conclusion_row = HB(R(f"{letter} = ", SZ), concl)
    stack = VStack([(defline, 0.0), (table, 14.0)])
    # bar under the table, conclusion (the listing) below the bar
    class BarredResult:
        def __init__(self, top, bottom, pad=4.0, gap=6.0):
            self.top, self.bottom, self.gap = top, bottom, gap
            self.bar = max(top.w, bottom.w) + 2 * pad
            self.w = self.bar
            self.ht = top.ht
            self.dp = top.dp + gap * 2 + 0.8 + bottom.ht + bottom.dp

        def emit(self, x, y):
            out = self.top.emit(x, y)
            by = y + self.top.dp + self.gap
            out.append(f'\\DLINE{{{fmt(x)}}}{{{fmt(by)}}}'
                       f'{{{fmt(x + self.bar)}}}{{{fmt(by)}}}{{0.6}}')
            out += self.bottom.emit(x + (self.bar - self.bottom.w) / 2,
                                     by + self.gap + self.bottom.ht)
            return out

    br = BarredResult(stack, conclusion_row)
    return br


piece_i = gen_piece("1b.i", f"{X_}{NOTDIV}{Y_}", F, F_)
piece_ii = gen_piece("1b.ii", f"{Y_}{NOTDIV}{X_}", G, G_)

sheets = lay_pieces([("1b.i", piece_i, 4, 10), ("1b.ii", piece_ii, 10, 8)])
folios = write_sheets(3060, sheets, OUT_SHEETS)
print("1b work sheets used:", folios)

