"""Generate answers306.tex + work sheet 3060 for problem 1b (divisibility
tables F, G over St(J)={0,1,3,4,7,9})."""
import sys, os
sys.path.insert(0, os.path.dirname(__file__))
from atoms import R, HB, Kern, VC, Infer, wrap, fmt
