#!/usr/bin/env python3
"""Generate answers314.tex for problem 2c: recursive definition of
rho(n)=2n(n+1). Template confirmed from Induction and Recursion Notes p.2-3
(bare BC/RcS labels immediately followed by the defining equation, e.g.
'BC phi(0):=1' / 'RcS AforAll n in N phi(n+1):=(n+1)phi(n)'). Both labels
are already printed on the exam (p314) -- only the equations are filled.

Derivation: rho(0)=2(0)(1)=0. rho(n+1)-rho(n) = 2(n+1)(n+2)-2n(n+1)
= 2(n+1)[(n+2)-n] = 4(n+1), so rho(n+1) = rho(n)+4(n+1). Verified n=0..2.
Fits entirely in the printed page's provided areas -- no work sheet needed
(the exam gives no 'continue on following pages' instruction for 2c,
unlike 1c/3c)."""
import sys, os
sys.path.insert(0, os.path.dirname(__file__))
from atoms import R, HB
from expr import N_, RHO

SZ = 11.04
OUT_PAGES = os.path.join(os.path.dirname(__file__), '..', 'pages')

lines314 = []
# BC area: label "BC" printed at (144.02, 275.80)
lines314 += R(f"{RHO}(0)≔0", SZ).emit(220, 275.80)
# RcS area: label "RcS" printed at (144.02, 395.80)
lines314 += R(f"∀{N_}∈ℕ {RHO}({N_}+1)≔{RHO}({N_})+4({N_}+1)", SZ).emit(220, 395.80)

with open(os.path.join(OUT_PAGES, 'answers314.tex'), 'w') as f:
    f.write('%% ===== answers314.tex — generated by gen_2c.py =====\n')
    f.write('\n'.join(lines314) + '\n')
print(f"wrote pages/answers314.tex ({len(lines314)} lines)")
