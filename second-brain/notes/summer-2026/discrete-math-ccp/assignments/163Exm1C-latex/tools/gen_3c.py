#!/usr/bin/env python3
"""Generate answers319.tex for problem 3c: induction proof that
AforAll n in N (4|rho(n)), using 2c's recursive definition
(BC: rho(0):=0; RcS: AforAll n in N rho(n+1):=rho(n)+4(n+1)).

Template confirmed from Induction and Recursion Notes pp.9-10 (the
beta(n)>alpha(n) worked example): SPf / state P(n) / BC block ending in a
bar under P(0) / RcS block with hypotheses P(0)P(1)...P(n) over a bar,
inline justified computation, bar under P(n+1) / Hence + induction-
principle bar + AforAll n in N (P(n)) / EPf. Fits entirely on the printed
page (319) -- ample blank space follows the RcS label, no work sheet
needed for a proof this short."""
import sys, os
sys.path.insert(0, os.path.dirname(__file__))
from atoms import R, HB, Infer, Chain, fmt
from expr import N_, RHO, P_
from stack import VStack

SZ = 11.04
OUT_PAGES = os.path.join(os.path.dirname(__file__), '..', 'pages')

C_LC = "\U0001D450"   # 𝑐 (witness variable for the inductive hypothesis)
Pn = f"{P_}({N_})"
P0 = f"{P_}(0)"
Pn1 = f"{P_}({N_}+1)"


def bar_chain(rows, sz=SZ, gap=6.0):
    atoms = [R(r, sz) if isinstance(r, str) else r for r in rows]

    class Chained:
        def __init__(self):
            ys, cy, first = [], 0.0, True
            for a in atoms:
                if first:
                    cy = a.ht; first = False
                else:
                    cy += gap + 0.8 + a.ht
                ys.append(cy)
                cy += a.dp
            self.ys = ys
            self.w = max(a.w for a in atoms)
            self.ht = atoms[0].ht
            self.dp = ys[-1] + atoms[-1].dp

        def emit(self, x, y):
            out = []
            for i, (a, ry) in enumerate(zip(atoms, self.ys)):
                out += a.emit(x, y + ry)
                if i < len(atoms) - 1:
                    by = y + ry + a.dp + gap
                    out.append(f'\\DLINE{{{fmt(x)}}}{{{fmt(by)}}}'
                               f'{{{fmt(x + self.w)}}}{{{fmt(by)}}}{{0.6}}')
            return out
    return Chained()


lines319 = []

# ---- SPf + statement of P(n), above the BC label ----
opening = VStack([
    (R("SPf", SZ, font='b'), 0.0),
    (R(f"∀{N_}∈ℕ {Pn}:⟺(4|{RHO}({N_}))", SZ), 4.0),
])
lines319 += opening.emit(220, 235.0)

# ---- BC block, next to the BC label (144.02, 282.80) ----
bc = bar_chain([f"{RHO}(0)=0", f"{RHO}(0)=(0)(4)", P0], sz=SZ, gap=5.0)
lines319 += bc.emit(220, 282.80)

# ---- RcS block, in the large space after the RcS label (144.02, 342.80) ----
# page-301's literal instruction ("=" signs aligned vertically, one below
# the other) applies here: the rho(n+1) computation is one Chain (first
# line bare, every later line starts with "="), not a horizontal run-on.
hyp_line = R(f"{P0} {P_}(1) ... {Pn}", SZ)
ih_and_chain = VStack([
    (R(f"{RHO}({N_})=4{C_LC}", SZ), 0.0),
    (Chain(R(f"{RHO}({N_}+1)", SZ), [
        R(f"{RHO}({N_})+4({N_}+1)", SZ),
        R(f"4{C_LC}+4({N_}+1)", SZ),
        R(f"({C_LC}+({N_}+1))(4)", SZ),
    ], sz=SZ), 10.0),
])
comp_chain = bar_chain([hyp_line, ih_and_chain, R(Pn1, SZ)], sz=SZ, gap=6.0)
lines319 += comp_chain.emit(220, 345.0)

# ---- Hence / induction-principle bar / EPf ----
# matches the notes' own citation of the induction principle (Induction and
# Recursion Notes p.2): nested bars, not an implication arrow -- P(0) beside
# a small copy of the RcS bar-shape (hyps -> P(n+1)), combined into one
# outer bar concluding AforAll n (P(n)).
hence_y = 345.0 + comp_chain.dp + 24.0
lines319 += R("Hence", SZ, font='b').emit(144.02, hence_y)
rcs_shape = Infer(hyp_line, R(Pn1, SZ))
induction_bar = Infer(HB(R(f"{P0}    (", SZ), rcs_shape, R(")", SZ)),
                       R(f"∀{N_}∈ℕ({Pn})", SZ))
lines319 += induction_bar.emit(220, hence_y + 22.0)
epf_y = hence_y + 22.0 + induction_bar.dp + 20.0
lines319 += R("EPf", SZ, font='b').emit(220, epf_y)

with open(os.path.join(OUT_PAGES, 'answers319.tex'), 'w') as f:
    f.write('%% ===== answers319.tex — generated by gen_3c.py =====\n')
    f.write('\n'.join(lines319) + '\n')
print(f"wrote pages/answers319.tex ({len(lines319)} lines)")
